def generate_functional_spec(language: str) -> Path:
    labels = LABELS[language]
    output = copy_template(
        "Functional_Specification.xlsx",
        f"Functional_Specification_IDTS_SAP01_{language}_v{FUNCTIONAL_VERSION}.xlsx",
    )
    wb = load_workbook(output)
    fill_cover(wb, labels, FUNCTIONAL_VERSION)
    fill_histories(wb, labels, FUNCTIONAL_VERSION)
    fill_function_overview(wb, labels)
    fill_process_flow(wb, labels)
    fill_screen_layout(wb, labels)
    fill_screen_definition(wb, labels)
    fill_message_definition(wb, labels)
    fill_processing_description(wb, labels)
    wb.save(output)
    return output


