def fill_screen_layout(wb, labels: dict):
    ws = wb["Screen Layout"]
    write(ws, "B2", "Screen Layout")
    write(ws, "B4", labels["screen_layout_note"], wrap=True)
    headers = [("C27", "No."), ("F27", "Field name"), ("N27", "Technical name"), ("S27", "Place"), ("AA27", "Logic")]
    for cell, value in headers:
        write(ws, cell, value)
    write(ws, "C28", 1)
    write(ws, "F28", "Main Create/Edit Fields", wrap=True)
    write(ws, "S28", "Object Page content", wrap=True)
    write(ws, "AA28", labels["screen_layout_note"], wrap=True)
    target_rows = [29, 30, 31, 33, 35, 37, 38, 39, 41, 43, 45, 47, 49, 50]
    for number, ((name, technical, place, logic), target_row) in enumerate(
        zip(labels["screen_items"][:14], target_rows), start=2
    ):
        if target_row > 45:
            copy_row_style(ws, 45, target_row, 35)
        write(ws, f"C{target_row}", number)
        write(ws, f"F{target_row}", name, wrap=True)
        write(ws, f"N{target_row}", technical, wrap=True)
        write(ws, f"S{target_row}", place, wrap=True)
        write(ws, f"AA{target_row}", logic, wrap=True)
        ws.row_dimensions[target_row].height = 34
    for row in [51, 52, 54]:
        for column in [3, 6, 14, 19, 27]:
            cell = ws.cell(row, column)
            if not isinstance(cell, MergedCell):
                cell.value = None


